describe('extractAtomClasses', () => {
  it('collects subject classes through layers, media, supports and container groups', () => {
    const atoms = extractAtomClasses(STYLESHEET, 'x');
    expect([...atoms].sort()).toEqual(
      [
        'x27bzpr0',
        'x6dyjq0r',
        'x6h0uiwj',
        'x6qc2vzi',
        'x9qvl7nn',
        'xattr001',
        'xce3dr7w',
        'xcmgh2ln',
        'xcont001',
        'xioqujzj',
        'xnest001',
        'xo6613xh',
        'xq3vd17w',
        'xstr0ng1',
      ].sort(),
    );
  });

  it('does not count :not() exclusions, keyframes names, declarations, strings or comments', () => {
    const atoms = extractAtomClasses(STYLESHEET, 'x');
    for (const cls of [
      'xlyif4tl',
      'xyyhqh81',
      'xgxnnz45',
      'x75vegj9',
      'xfake001',
      'xdead000',
      'xcomment1',
      'xce3dr7wextra',
    ])
      expect(atoms.has(cls), cls).toBe(false);
    const analysis = analyzeStylesheet(STYLESHEET, 'x');
    expect([...analysis.exclusions].sort()).toEqual([
      'x9qvl7nn',
      'xce3dr7w',
      'xgxnnz45',
      'xlyif4tl',
      'xo6613xh',
      'xyyhqh81',
    ]);
    expect(analysis.keyframes).toEqual(['x75vegj9', 'xfake001']);
    expect(analysis.layerStatement).toEqual(['purser.tokens', 'purser.globals', 'purser.atoms']);
    expect(analysis.layerBlocks).toEqual(['purser.tokens', 'purser.globals', 'purser.atoms']);
    expect(analysis.groups).toBe(5);
  });

  it('respects the prefix and identifier boundaries', () => {
    const css =
      '.p1234567 { color: red } .x1234567 { color: red } .p1234567-x { color: red } .p12345 { color: red }';
    expect([...extractAtomClasses(css, 'p')]).toEqual(['p1234567']);
    expect([...extractAtomClasses(css, 'x')]).toEqual(['x1234567']);
    expect([...extractAtomClasses('.my-x1234567{color:red}', 'x')]).toEqual([]);
    expect(atomClassPattern('x').test('xce3dr7w')).toBe(true);
    expect(atomClassPattern('x').test('xce3dr7')).toBe(false);
    expect(atomClassPattern('a.b').test('a.b123456')).toBe(false);
  });

  it('handles minified output and nested :not() groups', () => {
    const css =
      '@layer t,g,a;@layer a{.xaaaaaaa:not(:hover):not(.xbbbbbbb){color:red}@media (width>=768px){.xccccccc{display:flex}}:is(.xddddddd, .xeeeeeee):not(.xfffffff > .xggggggg){margin:0}}';
    expect([...extractAtomClasses(css, 'x')].sort()).toEqual([
      'xaaaaaaa',
      'xccccccc',
      'xddddddd',
      'xeeeeeee',
    ]);
    expect(extractLayerStatement(css)).toEqual(['t', 'g', 'a']);
  });

  it('strips comments outside strings only', () => {
    expect(stripCssComments('a /* x */ { content: "/* not */" } /* unterminated')).toBe(
      'a   { content: "/* not */" }  ',
    );
  });

  it('recognises Purser stylesheets, also minified and with custom layer names', () => {
    expect(isPurserStylesheet(STYLESHEET)).toBe(true);
    expect(
      isPurserStylesheet(
        '@layer purser-tokens,purser-globals,purser-atoms;@layer purser-atoms{.x1{color:red}}',
      ),
    ).toBe(true);
    expect(
      isPurserStylesheet('@layer purser-tokens,purser-globals,purser-atoms;', {
        tokens: 'purser.tokens',
        globals: 'purser.globals',
        atoms: 'purser.atoms',
      }),
    ).toBe(false);
    expect(isPurserStylesheet('@layer base, components; .a{}')).toBe(false);
    expect(isPurserStylesheet('.a{}')).toBe(false);
  });
});

describe('extractHtmlClasses', () => {
  const HTML = `<!DOCTYPE html><html lang="en" class="__variable_1a2b3c dark"><body>
<div class="xce3dr7w x27bzpr0 card">a</div>
<button class='xo6613xh xunknownclass' aria-pressed="true">b</button>
<span class=xq3vd17w>c</span>
<p class="xtoolong12 x12345">d</p>
<script>self.__next_f.push([1,"5:[\\"$\\",\\"div\\",null,{\\"className\\":\\"xcont001 xnest001\\",\\"children\\":\\"x\\"}]\\n"])</script>
<script>self.__next_f.push([1,"6:[\\"$\\",\\"span\\",null,{\\"className\\": \\"xattr001\\"}]\\n"])</script>
</body></html>`;

  it('reads class attributes in every quoting style and className props in embedded RSC payloads', () => {
    expect([...extractHtmlClasses(HTML, 'x')].sort()).toEqual([
      'x27bzpr0',
      'xattr001',
      'xce3dr7w',
      'xcont001',
      'xnest001',
      'xo6613xh',
      'xq3vd17w',
    ]);
  });

  it('reads standalone RSC payloads', () => {
    const rsc =
      '0:["$","$L1",null,{"className":"xce3dr7w xstr0ng1","children":["$","p",null,{"className":"xq3vd17w"}]}]\n';
    expect([...extractHtmlClasses(rsc, 'x')].sort()).toEqual(['xce3dr7w', 'xq3vd17w', 'xstr0ng1']);
    expect(extractHtmlClasses('', 'x').size).toBe(0);
  });
});

describe('verifyAtoms', () => {
  it('reports missing, used and unused atoms per route', () => {
    const result = verifyAtoms({
      html: {
        '/': '<div class="xce3dr7w x27bzpr0 xzzzzz01"></div>',
        '/blog/[slug]':
          '<p class="xq3vd17w"></p><script>["$",{\\"className\\":\\"xnest001 xzzzzz01 xzzzzz02\\"}]</script>',
        '/empty': '<main></main>',
      },
      css: STYLESHEET,
      prefix: 'x',
    });
    expect(result.missing).toEqual({ '/': ['xzzzzz01'], '/blog/[slug]': ['xzzzzz01', 'xzzzzz02'] });
    expect(result.used).toEqual({
      '/': ['x27bzpr0', 'xce3dr7w'],
      '/blog/[slug]': ['xnest001', 'xq3vd17w'],
      '/empty': [],
    });
    expect(result.unused).toEqual([
      'x6dyjq0r',
      'x6h0uiwj',
      'x6qc2vzi',
      'x9qvl7nn',
      'xattr001',
      'xcmgh2ln',
      'xcont001',
      'xioqujzj',
      'xo6613xh',
      'xstr0ng1',
    ]);
  });

  it('is clean when every referenced class is declared', () => {
    const result = verifyAtoms({
      html: { '/': '<i class="xce3dr7w"></i>' },
      css: '.xce3dr7w{color:red}',
      prefix: 'x',
    });
    expect(result.missing).toEqual({});
    expect(result.unused).toEqual([]);
  });
});

describe('isPurserStylesheet after bundling', () => {
  it('recognises Lightning CSS output without the header comment or the ordering statement', async () => {
    const { isPurserStylesheet } = await import('./stylesheet');
    const bundled =
      '@layer purser.tokens{:root{--space-1:4px}}@layer purser.globals{body{margin:0}}@layer purser.atoms{.x1abcdef{display:flex}}';
    expect(isPurserStylesheet(bundled)).toBe(true);
    expect(
      isPurserStylesheet(bundled, {
        tokens: 'purser.tokens',
        globals: 'purser.globals',
        atoms: 'purser.atoms',
      }),
    ).toBe(true);
    expect(
      isPurserStylesheet(bundled, { tokens: 'ds.tokens', globals: 'ds.globals', atoms: 'ds.atoms' }),
    ).toBe(false);
    expect(isPurserStylesheet('.app{color:red}@layer base{a{color:blue}}')).toBe(false);
  });
});
