const FAKE_BUILD_MODULE = `
import fs from 'node:fs';
import path from 'node:path';
const KEY = ${JSON.stringify(FAKE_PURSER_KEY)};
const state = () => (globalThis[KEY] ??= { calls: [], watchers: [], next: null });
const CSS = ${JSON.stringify(FIXTURE_CSS)};
function result(options, writes) {
  const outFile = options.out ? path.resolve(options.projectDir, options.out) : null;
  const base = {
    css: CSS,
    diagnostics: [
      { severity: 'warning', message: 'axis "mode" is not exhaustive', file: path.resolve(options.projectDir, options.tokens ?? 'lib/tokens.ts'), line: 3, column: 5 },
    ],
    stats: { files: 2, atoms: 3, rules: 4, keyframes: 1, tokens: 1 },
    written: false,
    outFile,
  };
  const next = state().next;
  const merged = next ? { ...base, ...next } : base;
  state().next = null;
  if (writes && merged.css && outFile) {
    fs.mkdirSync(path.dirname(outFile), { recursive: true });
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : null;
    if (current !== merged.css) { fs.writeFileSync(outFile, merged.css); merged.written = true; }
  }
  return merged;
}
export async function build(options) { state().calls.push({ method: 'build', options }); return result(options, true); }
export async function check(options) { state().calls.push({ method: 'check', options }); return result({ ...options, out: undefined }, false); }
export async function watch(options, onResult) {
  state().calls.push({ method: 'watch', options });
  const watcher = { closed: false, emit: (r) => onResult(r), close() { watcher.closed = true; } };
  state().watchers.push(watcher);
  onResult(result(options, true));
  return watcher;
}
export function createBuilder(options) {
  return { run: () => build(options), projectDir: options.projectDir, tokensFile: options.tokens ? path.resolve(options.projectDir, options.tokens) : null, outFile: options.out ? path.resolve(options.projectDir, options.out) : null };
}
`;

export interface FakeProjectOptions {
  /** Install the fake `@avonao/purser` (default true). */
  purser?: boolean | { version?: string; strikeScript?: boolean };
  /** Install a fake `typescript` with this version (default `5.9.3`); `null` installs none. */
  typescript?: string | null;
  /** Extra files, relative to the project root. */
  files?: Record<string, string>;
}

export interface FakeProject {
  dir: string;
  cleanup(): void;
  write(file: string, content: string): string;
}

/** Creates a temporary project with fake host dependencies in `node_modules`. */
export function createFakeProject(options: FakeProjectOptions = {}): FakeProject {
  const dir = mkdtempSync(join(tmpdir(), 'hypdriv-purser-'));
  const write = (file: string, content: string) => {
    const full = join(dir, file);
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, content);
    return full;
  };
  write('package.json', JSON.stringify({ name: 'fake-app', private: true, type: 'module' }));
  const purser = options.purser ?? true;
  if (purser) {
    const settings = typeof purser === 'object' ? purser : {};
    write(
      'node_modules/@avonao/purser/package.json',
      JSON.stringify({
        name: '@avonao/purser',
        version: settings.version ?? '0.1.0',
        type: 'module',
        exports: {
          '.': './src/index.js',
          './build': { types: './types/build.d.ts', default: './src/build/index.js' },
          './package.json': './package.json',
        },
      }),
    );
    write('node_modules/@avonao/purser/src/index.js', 'export const css = {};\n');
    write('node_modules/@avonao/purser/src/build/index.js', FAKE_BUILD_MODULE);
    if (settings.strikeScript !== false) {
      write(
        'node_modules/@avonao/purser/scripts/strike-count.js',
        '(function install(global){ global.purserStrikeCount = function(){ return { struck: [], count: 0, rules: 7, skipped: [] }; }; })(globalThis);\npurserStrikeCount();\n',
      );
    }
  }
  if (options.typescript !== null) {
    write(
      'node_modules/typescript/package.json',
      JSON.stringify({ name: 'typescript', version: options.typescript ?? '5.9.3', main: './lib/typescript.js' }),
    );
    write('node_modules/typescript/lib/typescript.js', 'module.exports = {};\n');
  }
  for (const [file, content] of Object.entries(options.files ?? {})) write(file, content);
  return {
    dir,
    write,
    cleanup() {
      rmSync(dir, { recursive: true, force: true });
    },
  };
}
