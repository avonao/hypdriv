import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import type { PurserBuildOptions, PurserBuildResult } from '../purser-types';

/** State the fake `@avonao/purser/build` module shares with tests through `globalThis`. */
export interface FakePurserState {
  calls: Array<{ method: 'build' | 'check' | 'watch'; options: PurserBuildOptions }>;
  watchers: Array<{ closed: boolean; emit(result: PurserBuildResult): void; close(): void }>;
  /** Overrides merged into the next results. */
  next: Partial<PurserBuildResult> | null;
}

export const FAKE_PURSER_KEY = '__hypdrivFakePurser';

export function fakePurserState(): FakePurserState {
  const g = globalThis as Record<string, unknown>;
  if (!g[FAKE_PURSER_KEY]) g[FAKE_PURSER_KEY] = { calls: [], watchers: [], next: null } satisfies FakePurserState;
  return g[FAKE_PURSER_KEY] as FakePurserState;
}

export function resetFakePurser(): FakePurserState {
  const state = fakePurserState();
  state.calls.length = 0;
  state.watchers.length = 0;
  state.next = null;
  return state;
}

