import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';

/** Deploy targets the scaffolder supports. */
export type Platform = 'cloudflare' | 'vercel';

/** Template ids: one per platform, with or without Purser CSS. */
export type TemplateId = 'cloudflare' | 'cloudflare-purser' | 'vercel' | 'vercel-purser';

/** Each template is a runnable example app of the repository, built and audited in CI. */
export const TEMPLATE_SOURCES: Record<TemplateId, string> = {
  cloudflare: 'examples/basic',
  'cloudflare-purser': 'examples/with-purser',
  vercel: 'examples/vercel',
  'vercel-purser': 'examples/vercel-purser',
};

export function templateFor(platform: Platform, purser: boolean): TemplateId {
  return purser ? `${platform}-purser` : platform;
}

/** Placeholder for the project name inside templates. */
export const NAME = '__HYPDRIV_APP_NAME__';
/** Placeholder for the project name with `-` replaced by `_` (Analytics Engine datasets). */
export const NAME_UNDERSCORED = '__HYPDRIV_APP_NAME_UNDERSCORED__';

/** Build output, local state and secrets never copied into a template. */
const EXCLUDED = new Set([
  'node_modules',
  '.next',
  '.open-next',
  '.wrangler',
  '.hypdriv',
  '.vercel',
  '.dev.vars',
  '.env.local',
  '.env.development.local',
  '.env.production.local',
  'next-env.d.ts',
  'cloudflare-env.d.ts',
  '.turbo',
]);

export function excluded(rel: string): boolean {
  const parts = rel.split(sep);
  if (parts.some((p) => EXCLUDED.has(p))) return true;
  const base = parts[parts.length - 1] ?? '';
  if (base.endsWith('.tsbuildinfo') || base.endsWith('.hypdriv.bak')) return true;
  // Account-specific wrangler configurations and local env files (git-ignored in the examples).
  if (/^wrangler\..+\.local\.(jsonc?|toml)$/.test(base) || /^\.env(\..+)?\.local$/.test(base)) return true;
  if (/^\.dev\.vars\..+$/.test(base) && base !== '.dev.vars.example') return true;
  // Generated by Purser at build time.
  if (rel.split(sep).join('/') === 'app/purser.css') return true;
  return false;
}

function walk(dir: string, root = dir): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    const rel = relative(root, full);
    if (excluded(rel)) continue;
    if (statSync(full).isDirectory()) out.push(...walk(full, root));
    else out.push(rel);
  }
  return out;
}

/** Parses the `catalog:` block of `pnpm-workspace.yaml` (flat `name: range` entries). */
export function parseCatalog(yaml: string): Record<string, string> {
  const out: Record<string, string> = {};
  let inCatalog = false;
  for (const line of yaml.split(/\r?\n/)) {
    if (/^catalog:\s*$/.test(line)) {
      inCatalog = true;
      continue;
    }
    if (!inCatalog) continue;
    if (/^\S/.test(line)) break;
    const m = /^\s+("?)([^"#:\s][^"#:]*?)\1\s*:\s*([^#\s]+)/.exec(line);
    if (m) out[m[2]!] = m[3]!.replace(/^["']|["']$/g, '');
  }
  return out;
}

export interface PackageJsonContext {
  catalog: Record<string, string>;
  /** Versions of the workspace packages (`hypdriv`, `@hypdriv/*`). */
  workspace: Record<string, string>;
}

/** Rewrites an example's `package.json` for publication: no `catalog:`/`workspace:` protocols, placeholder name. */
export function transformPackageJson(source: string, ctx: PackageJsonContext): string {
  const pkg = JSON.parse(source) as Record<string, unknown>;
  pkg.name = NAME;
  pkg.version = '0.1.0';
  pkg.private = true;
  for (const field of ['dependencies', 'devDependencies', 'optionalDependencies', 'peerDependencies']) {
    const deps = pkg[field] as Record<string, string> | undefined;
    if (!deps) continue;
    for (const [name, range] of Object.entries(deps)) {
      if (range.startsWith('catalog:')) {
        const resolved = ctx.catalog[name];
        if (!resolved) throw new Error(`${name} uses catalog: but pnpm-workspace.yaml has no catalog entry`);
        deps[name] = resolved;
      } else if (range.startsWith('workspace:')) {
        const version = ctx.workspace[name];
        if (!version) throw new Error(`${name} uses workspace: but is not a workspace package`);
        deps[name] = `^${version}`;
      }
    }
  }
  return `${JSON.stringify(pkg, null, 2)}\n`;
}

/** Drops the monorepo-only `source` export condition from an example's `tsconfig.json`. */
export function transformTsconfig(source: string): string {
  const config = JSON.parse(source) as { compilerOptions?: Record<string, unknown> };
  if (config.compilerOptions) delete config.compilerOptions.customConditions;
  return `${JSON.stringify(config, null, 2)}\n`;
}

/** Replaces the example's own app name with placeholders (wrangler names, buckets, datasets, site name). */
export function templatize(text: string, exampleName: string): string {
  const underscored = exampleName.replace(/-/g, '_');
  return text.split(exampleName).join(NAME).split(underscored).join(NAME_UNDERSCORED);
}

/**
 * The `site` line of `hypdriv.config.ts`: the example's demo origin becomes a commented hint, since every
 * application has its own.
 */
export function transformHypdrivConfig(source: string): string {
  return source.replace(
    /site:\s*\{\s*name:\s*'([^']*)'\s*,\s*origin:\s*'[^']*'\s*\}/,
    (_m, name: string) =>
      `site: { name: '${name}' /* , origin: 'https://www.example.com' — canonical origin for sitemaps and enqueue() outside requests */ }`,
  );
}

/** The README keeps the example's instructions under the application's own title. */
export function transformReadme(source: string, id: TemplateId): string {
  const body = source.replace(/^# [^\n]*\n+/, '');
  return `# ${NAME}\n\nScaffolded with [create-hypdriv](https://github.com/avonao/hypdriv/tree/main/packages/create-hypdriv) from the \`${id}\` template.\n\n${body}`;
}

export interface SyncOptions {
  repoRoot: string;
  outDir: string;
}

/** Example app name as used in its wrangler/config files (`hypdriv-basic`, `hypdriv-vercel`, …). */
function exampleAppName(sourceDir: string): string {
  const config = readFileSync(join(sourceDir, 'hypdriv.config.ts'), 'utf8');
  const m = /site:\s*\{\s*name:\s*'([^']+)'/.exec(config);
  if (!m) throw new Error(`${sourceDir}/hypdriv.config.ts has no site.name`);
  return m[1]!;
}

/** Workspace package versions (`packages/*`). */
export function workspaceVersions(repoRoot: string): Record<string, string> {
  const out: Record<string, string> = {};
  const dir = join(repoRoot, 'packages');
  for (const name of readdirSync(dir)) {
    const file = join(dir, name, 'package.json');
    if (!existsSync(file)) continue;
    const pkg = JSON.parse(readFileSync(file, 'utf8')) as { name?: string; version?: string };
    if (pkg.name && pkg.version) out[pkg.name] = pkg.version;
  }
  return out;
}

/**
 * Copies every example into `outDir/<template>` ready for publication: build output and secrets excluded,
 * `.gitignore` stored as `_gitignore` (npm drops `.gitignore` from packages), versions pinned from the
 * workspace catalog, the app name replaced with placeholders. Returns the files per template.
 */
export function syncTemplates(options: SyncOptions): Record<TemplateId, string[]> {
  const catalog = parseCatalog(readFileSync(join(options.repoRoot, 'pnpm-workspace.yaml'), 'utf8'));
  const workspace = workspaceVersions(options.repoRoot);
  rmSync(options.outDir, { recursive: true, force: true });
  const result = {} as Record<TemplateId, string[]>;
  for (const [id, source] of Object.entries(TEMPLATE_SOURCES) as Array<[TemplateId, string]>) {
    const sourceDir = join(options.repoRoot, source);
    const appName = exampleAppName(sourceDir);
    const target = join(options.outDir, id);
    const files: string[] = [];
    for (const rel of walk(sourceDir)) {
      const from = join(sourceDir, rel);
      const posix = rel.split(sep).join('/');
      const outRel = posix === '.gitignore' ? '_gitignore' : posix;
      const to = join(target, outRel);
      mkdirSync(dirname(to), { recursive: true });
      if (posix === 'package.json')
        writeFileSync(to, transformPackageJson(readFileSync(from, 'utf8'), { catalog, workspace }));
      else if (posix === 'tsconfig.json') writeFileSync(to, transformTsconfig(readFileSync(from, 'utf8')));
      else if (/\.(ts|tsx|jsonc?|md|example|toml)$/.test(posix) || posix === '.gitignore') {
        let text = readFileSync(from, 'utf8');
        if (posix === 'hypdriv.config.ts') text = transformHypdrivConfig(text);
        if (posix === 'README.md') text = transformReadme(text, id);
        writeFileSync(to, templatize(text, appName));
      } else cpSync(from, to);
      files.push(outRel);
    }
    result[id] = files;
  }
  writeFileSync(
    join(options.outDir, 'manifest.json'),
    `${JSON.stringify({ hypdriv: workspace.hypdriv ?? null, templates: result }, null, 2)}\n`,
  );
  return result;
}
