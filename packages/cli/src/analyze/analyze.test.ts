describe('base64 VLQ', () => {
  it.each([
    ['A', [0]],
    ['C', [1]],
    ['D', [-1]],
    ['gB', [16]],
    ['hB', [-16]],
    ['2HwcrxB', [123, 456, -789]],
    ['2HwcqxB', [123, 456, 789]],
    ['AAgBC', [0, 0, 16, 1]],
  ])('decodes %s', (segment, values) => {
    expect(decodeVlq(segment)).toEqual(values);
    expect(encodeVlq(values)).toBe(segment);
  });

  it('round-trips large values without 32-bit overflow', () => {
    for (const v of [2 ** 30 - 1, -(2 ** 30), 2 ** 31 + 5, -(2 ** 33)])
      expect(decodeVlq(encodeVlq([v]))).toEqual([v]);
  });

  it('rejects invalid input', () => {
    expect(() => decodeVlq('!')).toThrow(/invalid/);
    expect(() => decodeVlq('g')).toThrow(/truncated/);
  });

  it('decodes mappings into absolute segments per line', () => {
    const lines = decodeMappings('AAAA,CAAC;;ECAE,GAAGA');
    expect(lines).toHaveLength(3);
    expect(lines[0]).toEqual([
      { generatedColumn: 0, source: 0, sourceLine: 0, sourceColumn: 0, name: null },
      { generatedColumn: 1, source: 0, sourceLine: 0, sourceColumn: 1, name: null },
    ]);
    expect(lines[1]).toEqual([]);
    expect(lines[2]).toEqual([
      { generatedColumn: 2, source: 1, sourceLine: 0, sourceColumn: 3, name: null },
      { generatedColumn: 5, source: 1, sourceLine: 0, sourceColumn: 6, name: 0 },
    ]);
  });
});

/** A hand-written bundle: three sources, a glue prefix and an unmapped line. */
function tinyBundle() {
  const line0 = 'var a=1;var b=2;'; // [0,8) source 0, [8,16) source 1
  const line1 = '/*glue*/'; // unmapped
  const line2 = 'pkg();xx'; // [0,6) source 2, [6,8) unmapped segment
  const code = [line0, line1, line2].join('\n');
  // line 0: col 0 → src 0; col 8 → src 1 (delta src +1)
  // line 2: col 0 → src 2 (delta +1 from src 1); col 6 → unmapped (1-field segment)
  const mappings = [
    `${encodeVlq([0, 0, 0, 0])},${encodeVlq([8, 1, 0, 0])}`,
    '',
    `${encodeVlq([0, 1, 0, 0])},${encodeVlq([6])}`,
  ].join(';');
  const map = {
    version: 3,
    sources: [
      'src/app.ts',
      'node_modules/.pnpm/react@19.2.0/node_modules/react/index.js',
      'node_modules/@scope/pkg/dist/index.js',
    ],
    mappings,
  };
  return { code, map };
}

describe('byte attribution', () => {
  it('attributes generated bytes to sources and counts the rest as unmapped', () => {
    const { code, map } = tinyBundle();
    const a = attributeBytes(code, map);
    expect(a.bySource.get(0)).toBe(8);
    expect(a.bySource.get(1)).toBe(8);
    expect(a.bySource.get(2)).toBe(6);
    // newline ×2 + glue line (8) + unmapped tail (2)
    expect(a.unmapped).toBe(12);
    expect([...a.bySource.values()].reduce((x, y) => x + y, 0) + a.unmapped).toBe(code.length);
  });

  it('clamps columns beyond the line length', () => {
    const a = attributeBytes('abc', { mappings: `${encodeVlq([0, 0, 0, 0])},${encodeVlq([10, 0, 0, 0])}` });
    expect(a.bySource.get(0)).toBe(3);
  });

  it('groups by package, detects duplicates and analyses the bundle', () => {
    expect(packageOf('node_modules/.pnpm/react@19.2.0/node_modules/react/index.js')).toMatchObject({
      name: 'react',
      version: '19.2.0',
    });
    expect(packageOf('../node_modules/@scope/pkg/dist/x.js')?.name).toBe('@scope/pkg');
    expect(packageOf('node_modules/a/node_modules/b/i.js')?.name).toBe('b');
    expect(packageOf('src/app.ts')).toBeNull();
    const agg = aggregatePackages(
      [
        { source: 'node_modules/.pnpm/react@19.2.0/node_modules/react/a.js', bytes: 10 },
        { source: 'node_modules/.pnpm/react@19.1.0/node_modules/react/a.js', bytes: 5 },
        { source: 'src/x.ts', bytes: 3 },
      ],
      18,
    );
    expect(agg.byPackage).toEqual([{ name: 'react', bytes: 15, share: 15 / 18 }]);
    expect(agg.duplicates).toEqual([{ name: 'react', versions: ['19.2.0', '19.1.0'] }]);
    expect(agg.appBytes).toBe(3);

    const { code, map } = tinyBundle();
    const analysis = analyzeWorkerBundle({
      file: 'worker.js',
      code,
      map: parseSourceMap(JSON.stringify(map)),
    });
    expect(analysis).toMatchObject({ raw: code.length, sourceMap: true, appBytes: 8, unmapped: 12 });
    expect(analysis.largestModules.map((m) => m.source)).toEqual([
      'src/app.ts',
      'node_modules/.pnpm/react@19.2.0/node_modules/react/index.js',
      'node_modules/@scope/pkg/dist/index.js',
    ]);
    expect(analysis.byPackage.map((p) => p.name)).toEqual(['react', '@scope/pkg']);
    expect(analysis.gzip).toBe(gzipSize(code));
  });

  it('rejects unusable source maps', () => {
    expect(parseSourceMap('{')).toBeNull();
    expect(parseSourceMap('{"version":2,"sources":[],"mappings":""}')).toBeNull();
    expect(parseSourceMap('{"version":3,"sections":[],"sources":[],"mappings":""}')).toBeNull();
  });
});

describe('sizes and startup indicators', () => {
  it('computes gzip at level 6', () => {
    const text = 'hello world '.repeat(200);
    const size = gzipSize(text);
    expect(size).toBeLessThan(text.length / 10);
    expect(gzipSync(text, { level: 6 }).length).toBe(size);
    expect(gunzipSync(gzipSync(text)).toString()).toBe(text);
  });

  it('counts top-level awaits outside functions, strings and comments', () => {
    const code =
      // biome-ignore lint/suspicious/noTemplateCurlyInString: JavaScript source text under test
      "await init();\nfunction f() { await x(); }\nconst s = 'await';\n// await\n/* await */\nconst t = `${await y}`;\nawait (async () => { await z(); })();\nfoo.await();\n";
    expect(countTopLevelAwaits(code)).toBe(2);
    expect(countTopLevelAwaits('await a;'.repeat(10), 16)).toBe(2);
  });

  it('parses wrangler size output', () => {
    expect(
      parseWranglerSizes('Total Upload: 4321.50 KiB / gzip: 987.25 KiB\nYour worker has access to'),
    ).toEqual({ total: Math.round(4321.5 * 1024), gzip: Math.round(987.25 * 1024) });
    expect(parseWranglerSizes('nothing')).toBeNull();
  });
});

describe('esbuild metafile', () => {
  it('summarises inputs by output contribution and package', () => {
    const meta = parseMetafile({
      inputs: {
        'node_modules/next/dist/server.js': { bytes: 5000 },
        'node_modules/react/index.js': { bytes: 2000 },
        'app/page.tsx': { bytes: 300 },
      },
      outputs: {
        'handler.mjs': {
          bytes: 4100,
          inputs: {
            'node_modules/next/dist/server.js': { bytesInOutput: 3000 },
            'node_modules/react/index.js': { bytesInOutput: 1000 },
            'app/page.tsx': { bytesInOutput: 100 },
          },
        },
      },
    });
    expect(meta).not.toBeNull();
    const summary = summarizeMetafile(meta!, 'handler.mjs.meta.json', { limit: 2 });
    expect(summary).toMatchObject({ inputs: 3, totalInputBytes: 7300, totalOutputBytes: 4100 });
    expect(summary.largestInputs.map((i) => [i.path, i.bytesInOutput])).toEqual([
      ['node_modules/next/dist/server.js', 3000],
      ['node_modules/react/index.js', 1000],
    ]);
    expect(summary.byPackage.map((p) => p.name)).toEqual(['next', 'react', '(app)']);
    expect(parseMetafile({})).toBeNull();
  });
});

describe('Vercel Build Output', () => {
  it('measures functions, follows filePathMap, collapses symlinked functions and flags oversize bundles', async () => {
    const p = tempProject({
      '.vercel/output/config.json': JSON.stringify({ version: 3 }),
      '.vercel/output/functions/index.func/.vc-config.json': JSON.stringify({
        runtime: 'nodejs22.x',
        handler: 'index.js',
        regions: ['iad1'],
        maxDuration: 60,
        filePathMap: {
          'node_modules/next/dist/server.js':
            'node_modules/.pnpm/next@16.4.3/node_modules/next/dist/server.js',
          'node_modules/gone.js': 'node_modules/gone.js',
        },
      }),
      '.vercel/output/functions/index.func/index.js': 'a'.repeat(1000),
      'node_modules/.pnpm/next@16.4.3/node_modules/next/dist/server.js': 'n'.repeat(4000),
      '.vercel/output/functions/api/edge.func/.vc-config.json': JSON.stringify({
        runtime: 'edge',
        entrypoint: 'index.js',
      }),
      '.vercel/output/functions/api/edge.func/index.js': 'export default () => new Response("x");'.repeat(50),
      '.vercel/output/static/_next/static/chunks/a.js': 'c'.repeat(300),
    });
    const { symlinkSync } = await import('node:fs');
    symlinkSync(
      join(p.dir, '.vercel/output/functions/index.func'),
      join(p.dir, '.vercel/output/functions/index.rsc.func'),
    );
    const analysis = analyzeVercelOutput(join(p.dir, '.vercel/output'), { buildRoot: p.dir });
    expect(analysis.functions).toHaveLength(2);
    const index = analysis.functions.find((f) => f.name === 'index')!;
    expect(index).toMatchObject({
      runtime: 'nodejs22.x',
      kind: 'node',
      regions: ['iad1'],
      maxDuration: 60,
      missingFiles: 1,
      status: 'ok',
      routes: ['/'],
    });
    expect(index.bytes).toBe(
      1000 + 4000 + Buffer.byteLength(p.read('.vercel/output/functions/index.func/.vc-config.json')),
    );
    expect(index.topPackages[0]).toEqual({ name: 'next', bytes: 4000 });
    const edge = analysis.functions.find((f) => f.kind === 'edge')!;
    expect(edge.gzip).toBeGreaterThan(0);
    expect(edge.gzip!).toBeLessThan(edge.bytes);
    expect(analysis.static).toEqual({ files: 1, bytes: 300 });
    expect(analysis.largest?.name).toBe('index');
  });
});

describe('hypdriv analyze', () => {
  it('runs wrangler --dry-run through the injected exec, attributes the bundle and updates the manifest', async () => {
    const p = openNextProject({
      'hypdriv.config.ts': "export default { budgets: { worker: { gzip: '1kb' } } };\n",
    });
    p.write('.open-next/worker.js', 'export default {}');
    await writeManifest(p.dir, await fixtureManifest());
    const { code: bundle, map } = tinyBundle();
    const calls: Array<{ command: string; args: string[] }> = [];
    const io = memoryIO(p.dir, {
      exec: async (command, args, options) => {
        calls.push({ command, args });
        const out = join(options.cwd, '.hypdriv/worker-build');
        mkdirSync(out, { recursive: true });
        writeFileSync(join(out, 'hypdriv.worker.js'), bundle);
        writeFileSync(join(out, 'hypdriv.worker.js.map'), JSON.stringify(map));
        return { code: 0, stdout: 'Total Upload: 1.00 KiB / gzip: 0.50 KiB', stderr: '' };
      },
    });
    const exit = await runCommand('analyze', ['--json'], io);
    expect(calls).toEqual([
      {
        command: 'pnpm',
        args: [
          'exec',
          'wrangler',
          'deploy',
          '--dry-run',
          '--outdir',
          '.hypdriv/worker-build',
          '--config',
          join(p.dir, 'wrangler.jsonc'),
        ],
      },
    ]);
    const out = JSON.parse(io.out);
    expect(out.platform).toBe('cloudflare');
    expect(out.worker).toMatchObject({
      raw: bundle.length,
      sourceMap: true,
      wranglerReported: { total: 1024, gzip: 512 },
    });
    expect(out.routes.length).toBeGreaterThan(3);
    expect(out.budgets.find((b: { id: string }) => b.id === 'worker:gzip')).toMatchObject({ limit: 1000 });
    expect(exit).toBe(0);
    const manifest = JSON.parse(p.read('.hypdriv/manifest.json'));
    expect(manifest.weights.worker.raw).toBe(bundle.length);
    expect(manifest.buildId).toBe('I1wNd3pCoOLr16ruV6B_d');
    expect(JSON.parse(p.read('.hypdriv/analyze.json')).worker.raw).toBe(bundle.length);

    // second run reuses the fresh bundle without spawning wrangler
    const again = memoryIO(p.dir, {
      exec: async () => {
        throw new Error('should not run');
      },
    });
    expect(await runCommand('analyze', ['--worker'], again)).toBe(0);
    expect(again.out).toContain('Worker bundle');
    expect(again.out).toContain('Largest packages');
  });

  it('reports wrangler failures and skips building with --no-build', async () => {
    const p = openNextProject();
    p.write('.open-next/worker.js', 'export default {}');
    const failing = memoryIO(p.dir, {
      exec: async () => ({ code: 1, stdout: '', stderr: '✘ [ERROR] Could not resolve "x"' }),
    });
    expect(await runCommand('analyze', [], failing)).toBe(1);
    expect(failing.err).toContain('Could not resolve');
    const noBuild = memoryIO(p.dir);
    expect(await runCommand('analyze', ['--no-build', '--json'], noBuild)).toBe(0);
    expect(JSON.parse(noBuild.out).notes.join(' ')).toContain('--no-build');
  });

  it('reports Vercel function bundles on the Vercel platform', async () => {
    const p = tempProject({
      'package.json': JSON.stringify({ name: 'site', dependencies: { next: '16.4.3' } }),
      'vercel.json': '{}',
      '.vercel/output/config.json': '{"version":3}',
      '.vercel/output/functions/index.func/.vc-config.json': JSON.stringify({
        runtime: 'nodejs22.x',
        handler: 'index.js',
      }),
      '.vercel/output/functions/index.func/index.js': 'x'.repeat(2000),
    });
    const io = memoryIO(p.dir);
    expect(await runCommand('analyze', ['--json'], io)).toBe(0);
    const out = JSON.parse(io.out);
    expect(out.platform).toBe('vercel');
    expect(out.worker).toBeNull();
    expect(out.vercel.functions[0]).toMatchObject({ name: 'index', kind: 'node', status: 'ok' });
    const text = memoryIO(p.dir);
    await runCommand('analyze', [], text);
    expect(text.out).toContain('Vercel functions');
  });
});
