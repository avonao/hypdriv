import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, posix, relative } from 'node:path';
import { ensureAssetsIgnore } from '@hypdriv/vite';

/** Files of the client output that configure Cloudflare or hold the Worker: never uploaded as static assets. */
export const WORKER_FILES = ['_worker.js', '_routes.json'];

/** The server entry the Cloudflare build produces (`src/entry.cloudflare.tsx`). */
export function findCloudflareEntry(outputEntries: string[]): string | undefined {
  return outputEntries.find((name) => /^entry\.cloudflare\.[cm]?js$/.test(name));
}

/** Whether built code exports a default (`export default …` or `export { x as default }`). */
export function hasDefaultExport(code: string): boolean {
  return /\bexport\s+default\b/.test(code) || /\bexport\s*\{[^}]*\bas\s+default\b[^}]*\}/.test(code);
}

/** The source of `dist/_worker.js`: the Worker module of the server entry and its Durable Object classes. */
export function workerSource(importPath: string): string {
  const specifier = JSON.stringify(importPath);
  return [
    '// Generated by @hypdriv/qwik: the Worker is the default export of the Cloudflare entry.',
    `export * from ${specifier};`,
    `export { default } from ${specifier};`,
    '',
  ].join('\n');
}

/**
 * Writes `dist/_worker.js` (wrangler's `main`) next to the static assets and keeps it out of the assets upload.
 * Returns the file written.
 */
export function writeCloudflareWorker(input: {
  clientDir: string;
  serverDir: string;
  entryFile: string;
  error: (message: string) => void;
}): string {
  const entry = join(input.serverDir, input.entryFile);
  const code = existsSync(entry) ? readFileSync(entry, 'utf8') : '';
  if (!hasDefaultExport(code))
    input.error(
      `@hypdriv/qwik: ${input.entryFile} must export the Worker as its default export: \`export default createQwikRouter({ render })\` with createQwikRouter from '@hypdriv/qwik/middleware/cloudflare'`,
    );
  const importPath = posix.join(
    ...relative(input.clientDir, input.serverDir).split(/[\\/]/).filter(Boolean),
    input.entryFile,
  );
  const file = join(input.clientDir, '_worker.js');
  writeFileSync(file, workerSource(importPath.startsWith('.') ? importPath : `./${importPath}`));
  ensureAssetsIgnore(input.clientDir, WORKER_FILES);
  return file;
}
