import { existsSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, extname, join, relative, resolve, sep } from 'node:path';
import { pathToFileURL } from 'node:url';
import { loadConfig } from '../config/define';
import type { ResolvedConfig } from '../config/resolved';
import type { HypDrivConfig } from '../config/types';
import { assertManifest, type HypManifest } from '../manifest/types';

export const MANIFEST_DIR = '.hypdriv';
export const MANIFEST_FILE = 'manifest.json';

/** Finds the nearest directory containing `package.json` starting from `start`. */
export function findProjectRoot(start: string = process.cwd()): string {
  let dir = resolve(start);
  for (;;) {
    if (existsSync(join(dir, 'package.json'))) return dir;
    const parent = dirname(dir);
    if (parent === dir) return resolve(start);
    dir = parent;
  }
}

/** Finds the workspace root (pnpm-workspace.yaml / .git / lockfile) above a project root. */
export function findRepoRoot(start: string = process.cwd()): string {
  let dir = resolve(start);
  let found = dir;
  for (;;) {
    if (
      existsSync(join(dir, 'pnpm-workspace.yaml')) ||
      existsSync(join(dir, '.git')) ||
      existsSync(join(dir, 'pnpm-lock.yaml')) ||
      existsSync(join(dir, 'package-lock.json')) ||
      existsSync(join(dir, 'yarn.lock')) ||
      existsSync(join(dir, 'bun.lock')) ||
      existsSync(join(dir, 'bun.lockb'))
    ) {
      found = dir;
      if (existsSync(join(dir, 'pnpm-workspace.yaml')) || existsSync(join(dir, '.git'))) return dir;
    }
    const parent = dirname(dir);
    if (parent === dir) return found;
    dir = parent;
  }
}

export function manifestPath(projectDir: string): string {
  return join(projectDir, MANIFEST_DIR, MANIFEST_FILE);
}

interface CacheEntry {
  mtimeMs: number;
  manifest: HypManifest;
}
const cache = new Map<string, CacheEntry>();

/** Reads and validates the manifest synchronously; returns null when absent. Cached by mtime. */
export function readManifestSync(projectDir: string): HypManifest | null {
  const file = manifestPath(projectDir);
  if (!existsSync(file)) return null;
  const mtimeMs = statSync(file).mtimeMs;
  const hit = cache.get(file);
  if (hit && hit.mtimeMs === mtimeMs) return hit.manifest;
  const parsed: unknown = JSON.parse(readFileSync(file, 'utf8'));
  assertManifest(parsed);
  cache.set(file, { mtimeMs, manifest: parsed });
  return parsed;
}

export async function readManifest(projectDir: string): Promise<HypManifest | null> {
  return readManifestSync(projectDir);
}

/** Writes the manifest (JSON + an ESM module for bundlers without JSON import support). */
export async function writeManifest(
  projectDir: string,
  manifest: HypManifest,
): Promise<{ json: string; module: string }> {
  const dir = join(projectDir, MANIFEST_DIR);
  await mkdir(dir, { recursive: true });
  const json = join(dir, MANIFEST_FILE);
  const module = join(dir, 'manifest.js');
  const text = JSON.stringify(manifest, null, 2);
  await writeFile(json, text);
  await writeFile(module, `// Generated by Hypdriv. Do not edit.\nexport default ${text};\n`);
  await writeFile(
    join(dir, 'manifest.d.ts'),
    `import type { HypManifest } from '@hypdriv/core';\ndeclare const manifest: HypManifest;\nexport default manifest;\n`,
  );
  cache.delete(json);
  return { json, module };
}

const CONFIG_FILES = ['hypdriv.config.ts', 'hypdriv.config.mts', 'hypdriv.config.js', 'hypdriv.config.mjs'];

export function findConfigFile(projectDir: string): string | null {
  for (const name of CONFIG_FILES) {
    const file = join(projectDir, name);
    if (existsSync(file)) return file;
  }
  return null;
}

const TS_EXTENSIONS = new Set(['.ts', '.mts', '.cts']);

function isTypeScriptLoadError(err: unknown): boolean {
  const e = err as { code?: string; name?: string; message?: string };
  return (
    e?.code === 'ERR_UNKNOWN_FILE_EXTENSION' ||
    e?.code === 'ERR_UNSUPPORTED_NODE_MODULES_TYPE_STRIPPING' ||
    e?.name === 'SyntaxError' ||
    /Unknown file extension|strip-types|type stripping/i.test(e?.message ?? '')
  );
}

/**
 * Node's ES module loader does not guess file extensions: `import './shared'` in a TypeScript config fails with
 * `ERR_MODULE_NOT_FOUND` even though `shared.ts` sits next to it. Returns an error that names the fix, or null
 * when `err` is something else.
 */
export function explainExtensionlessImport(err: unknown): Error | null {
  const e = err as { code?: string; message?: string };
  if (e?.code !== 'ERR_MODULE_NOT_FOUND') return null;
  const m = /Cannot find module '([^']+)' imported from (\S+)/.exec(e.message ?? '');
  if (!m?.[1] || !m[2] || extname(m[1])) return null;
  const [, target, importer] = m;
  for (const ext of ['.ts', '.mts', '.tsx', '.js', '.mjs']) {
    if (!existsSync(target + ext)) continue;
    let spec = relative(dirname(importer), target).split(sep).join('/');
    if (!spec.startsWith('.')) spec = `./${spec}`;
    return new Error(
      `${basename(importer)} imports '${spec}' without a file extension. hypdriv.config is loaded by Node's ES module loader, which needs explicit extensions on relative imports: write '${spec}${ext}'.`,
      { cause: err },
    );
  }
  return null;
}

/**
 * Imports a config module. TypeScript files use the runtime's native type stripping (Node 22.18+ /
 * 23.6+); on runtimes without it the file is stripped with `node:module`'s `stripTypeScriptTypes`
 * (Node 22.13+) into a sibling temporary `.mjs` so relative imports keep resolving.
 */
export async function importConfigModule<T = unknown>(file: string): Promise<T> {
  const href = `${pathToFileURL(file).href}?t=${Math.trunc(statSync(file).mtimeMs * 1000)}`;
  try {
    return (await import(/* @vite-ignore */ /* webpackIgnore: true */ /* turbopackIgnore: true */ href)) as T;
  } catch (err) {
    const explained = explainExtensionlessImport(err);
    if (explained) throw explained;
    if (!TS_EXTENSIONS.has(extname(file)) || !isTypeScriptLoadError(err)) throw err;
    const mod = (await import('node:module')) as {
      stripTypeScriptTypes?: (code: string, options?: { mode?: 'strip' | 'transform' }) => string;
    };
    if (typeof mod.stripTypeScriptTypes !== 'function') {
      throw new Error(
        `cannot load ${basename(file)}: this Node.js version cannot run TypeScript. Use Node 22.18+ or rename the file to .mjs (${(err as Error).message})`,
      );
    }
    const js = mod.stripTypeScriptTypes(readFileSync(file, 'utf8'), { mode: 'transform' });
    const tmp = join(dirname(file), `.${basename(file, extname(file))}.${process.pid}.${Date.now()}.mjs`);
    writeFileSync(tmp, js);
    try {
      return (await import(
        /* @vite-ignore */ /* webpackIgnore: true */ /* turbopackIgnore: true */ pathToFileURL(tmp).href
      )) as T;
    } finally {
      rmSync(tmp, { force: true });
    }
  }
}

/**
 * Loads `hypdriv.config.*` (or an explicit `file`) and resolves it. Accepts `export default` or a
 * named `config` export.
 */
export async function loadConfigFile(
  projectDir: string,
  file: string | null = findConfigFile(projectDir),
): Promise<{ file: string | null; config: HypDrivConfig; resolved: ResolvedConfig }> {
  if (!file) {
    const resolved = loadConfig({});
    return { file: null, config: {}, resolved };
  }
  const mod = await importConfigModule<{ default?: HypDrivConfig; config?: HypDrivConfig }>(file);
  const config = mod.default ?? mod.config ?? {};
  const resolved = loadConfig(config);
  return { file, config, resolved };
}

export interface PackageInfo {
  name: string | null;
  version: string | null;
  dependencies: Record<string, string>;
  devDependencies: Record<string, string>;
  scripts: Record<string, string>;
  packageManager: string | null;
}

export function readPackageJson(dir: string): PackageInfo | null {
  const file = join(dir, 'package.json');
  if (!existsSync(file)) return null;
  const pkg = JSON.parse(readFileSync(file, 'utf8')) as Record<string, unknown>;
  return {
    name: typeof pkg.name === 'string' ? pkg.name : null,
    version: typeof pkg.version === 'string' ? pkg.version : null,
    dependencies: (pkg.dependencies as Record<string, string>) ?? {},
    devDependencies: (pkg.devDependencies as Record<string, string>) ?? {},
    scripts: (pkg.scripts as Record<string, string>) ?? {},
    packageManager: typeof pkg.packageManager === 'string' ? pkg.packageManager : null,
  };
}

/** Resolves the installed version of a dependency from the project's node_modules. */
export function installedVersion(projectDir: string, name: string): string | null {
  let dir = resolve(projectDir);
  for (;;) {
    const file = join(dir, 'node_modules', name, 'package.json');
    if (existsSync(file)) {
      try {
        return (JSON.parse(readFileSync(file, 'utf8')) as { version?: string }).version ?? null;
      } catch {
        return null;
      }
    }
    const parent = dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

/** Reads JSON with a typed fallback. */
export async function readJson<T>(file: string, fallback: T): Promise<T> {
  try {
    return JSON.parse(await readFile(file, 'utf8')) as T;
  } catch {
    return fallback;
  }
}

export function detectPackageManager(projectDir: string): 'pnpm' | 'npm' | 'yarn' | 'bun' {
  const root = findRepoRoot(projectDir);
  const pkg = readPackageJson(projectDir) ?? readPackageJson(root);
  const pm = pkg?.packageManager?.split('@')[0];
  if (pm === 'pnpm' || pm === 'yarn' || pm === 'bun' || pm === 'npm') return pm;
  for (const dir of [projectDir, root]) {
    if (existsSync(join(dir, 'pnpm-lock.yaml'))) return 'pnpm';
    if (existsSync(join(dir, 'bun.lock')) || existsSync(join(dir, 'bun.lockb'))) return 'bun';
    if (existsSync(join(dir, 'yarn.lock'))) return 'yarn';
    if (existsSync(join(dir, 'package-lock.json'))) return 'npm';
  }
  return 'npm';
}
